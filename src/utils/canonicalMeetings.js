/**
 * Filtruje techniczne wpisy organizacyjne (np. DEADLINE, przypomnienia, terminy zgłoszeń)
 */
export function filterLegitimateMeetings(meetings = [], orgId = 'skn-psychoonkologia') {
  if (!Array.isArray(meetings) || meetings.length === 0) return getCanonicalMeetingsForOrg(orgId || 'skn-psychoonkologia');

  const technicalKeywords = [
    'deadline',
    'termin',
    'weryfikacja',
    'przypomnienie',
    'ankieta',
    'zamknięcie',
    'odwołane',
    'techniczny',
    'testowe',
    'próba połączenia',
  ];

  const legitimate = meetings.filter(m => {
    const title = (m?.title || m?.name || '').toLowerCase();
    const type = (m?.type || '').toLowerCase();
    const isTech = technicalKeywords.some(kw => title.includes(kw) || type.includes(kw));
    return !isTech;
  });

  return legitimate.length > 0 ? legitimate : getCanonicalMeetingsForOrg(orgId || 'skn-psychoonkologia');
}

